def rolling_key(base):
    """Legacy â€” kept for reference, but NOT used by _xd() decoder."""
    return [base, base ^ 0x37, base ^ 0x91, base ^ 0xC5]

def xor_encode(text, base_key=0x5A):
    """Must match _xd() in ares_strings.h: k = (key ^ ((i * 0x13 + 0x07) & 0xFF))"""
    return [ord(c) ^ ((base_key ^ ((i * 0x13 + 0x07) & 0xFF)) & 0xFF) for i, c in enumerate(text)]

def aes_gcm_encrypt(plaintext_bytes, key_bytes):
    """AES-256-GCM encrypt. Returns (nonce_12, ciphertext+tag_16).
    Ciphertext layout: nonce(12) || ciphertext || tag(16)."""
    nonce = os.urandom(12)
    if HAS_PYCRYPTODOME:
        cipher = AES.new(key_bytes, AES.MODE_GCM, nonce=nonce)
        ct, tag = cipher.encrypt_and_digest(plaintext_bytes)
        return nonce, ct + tag
    elif HAS_CRYPTOGRAPHY:
        aesgcm = AESGCM(key_bytes)
        ct_with_tag = aesgcm.encrypt(nonce, plaintext_bytes, None)
        return nonce, ct_with_tag
    else:
        raise RuntimeError("No AES library available. Install pycryptodome or cryptography.")

def fmt_bytes(data):
    return "{" + ",".join(f"0x{b:02x}" for b in data) + "}"

